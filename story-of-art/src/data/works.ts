export const works: Work[] = catalog.map((work) => ({
  ...work,
  ...(extras[work.id] ?? {}),
}));

const byId = new Map(works.map((work) => [work.id, work]));

export function getWork(id: string): Work {
  const work = byId.get(id);
  if (!work) throw new Error(`missing work ${id}`);
  return work;
}
